#!/usr/bin/env node
/**
 * Generate the checked-in OpenUI catalog artifacts from catalog.ts.
 *
 * `catalog.ts` is the source: Zod prop schemas drive the parser (via
 * createLibrary), parser signatures, and the generated skill/pointer. Run this
 * after changing the catalog; CI runs it with --check and fails on drift.
 *
 * Usage:
 *   node scripts/generate-openui-catalog.mjs
 *   node scripts/generate-openui-catalog.mjs --check
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");

const OUTPUTS = {
	generatedTs: path.join(ROOT, "src/lib/agent/openui/generated/catalog.ts"),
	snapshot: path.join(ROOT, "test/fixtures/openui-catalog.snapshot.json"),
};

async function loadCatalog() {
	const server = await createServer({
		configFile: false,
		root: ROOT,
		logLevel: "error",
		appType: "custom",
		server: { middlewareMode: true },
		optimizeDeps: { noDiscovery: true, include: [] },
	});
	try {
		const mod = await server.ssrLoadModule("/src/lib/agent/openui/catalog.ts");
		return {
			library: mod.uiBlockLibrary,
			names: mod.OPENUI_COMPONENT_NAMES,
		};
	} finally {
		await server.close();
	}
}

function buildArtifacts(library, names) {
	const spec = library.toSpec();
	const components = names.map((name) => {
		const entry = spec.components[name];
		if (!entry) {
			throw new Error(`catalog component missing from toSpec(): ${name}`);
		}
		return {
			name,
			signature: entry.signature,
			description: entry.description ?? "",
		};
	});

	const signatures = Object.fromEntries(
		components.map(({ name, signature }) => [name, signature]),
	);

	const generatedTs = `// Generated by scripts/generate-openui-catalog.mjs — do not edit.
export const OPENUI_COMPONENT_NAMES = ${JSON.stringify(names)} as const;

export type OpenUiComponentName = (typeof OPENUI_COMPONENT_NAMES)[number];

export const OPENUI_COMPONENT_SIGNATURES: Record<OpenUiComponentName, string> = ${JSON.stringify(signatures, null, "\t")};
`;

	const snapshot = `${JSON.stringify(
		{ componentCount: components.length, components },
		null,
		"\t",
	)}\n`;

	return {
		[OUTPUTS.generatedTs]: generatedTs,
		[OUTPUTS.snapshot]: snapshot,
	};
}

function main() {
	return loadCatalog().then(({ library, names }) => {
		const artifacts = buildArtifacts(library, names);
		const stale = [];

		for (const [file, content] of Object.entries(artifacts)) {
			const current = fs.existsSync(file)
				? fs.readFileSync(file, "utf8")
				: null;
			if (current === content) continue;
			stale.push(path.relative(ROOT, file));
			if (!CHECK) {
				fs.mkdirSync(path.dirname(file), { recursive: true });
				fs.writeFileSync(file, content);
			}
		}

		if (CHECK && stale.length > 0) {
			console.error(
				"Generated OpenUI catalog is stale:\n" +
					stale.map((file) => `  ${file}`).join("\n") +
					"\nRun: node scripts/generate-openui-catalog.mjs",
			);
			process.exitCode = 1;
			return;
		}

		if (stale.length === 0) {
			console.log("OpenUI catalog artifacts are current.");
		} else {
			console.log(`Wrote ${stale.length} OpenUI catalog artifact(s).`);
		}
	});
}

main().catch((error) => {
	console.error(error);
	process.exitCode = 1;
});
